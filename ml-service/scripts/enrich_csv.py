#!/usr/bin/env python3
"""
scripts/enrich_csv.py

Fixes the metadata.csv generated by convert_and_rename.py:

1. Replaces all "Unknown" values with sensible defaults per category folder.
2. Fixes the folder mismatch: 06_portfolio_samples → 06_designer_portfolio.
3. Reassigns sequential unique IDs across all rows (img_0001 ... img_1262).
4. Writes the fixed CSV back to seed_data/metadata.csv (backs up the original first).

Run once:
  python scripts/enrich_csv.py

Then optionally open the CSV and hand-tune individual rows before seeding.
"""

